package com.myjavaworld.jftp;

import java.io.File;
import java.io.FileInputStream;
import java.io.IOException;
import java.io.ObjectInputStream;
import java.io.ObjectOutputStream;
import java.io.Serializable;
import java.nio.file.Files;
import java.security.InvalidKeyException;
import java.security.NoSuchAlgorithmException;
import java.util.ArrayList;
import java.util.List;

import javax.crypto.BadPaddingException;
import javax.crypto.Cipher;
import javax.crypto.IllegalBlockSizeException;
import javax.crypto.NoSuchPaddingException;
import javax.crypto.SealedObject;
import javax.crypto.spec.SecretKeySpec;

/**
 * A Class used to serialize/deserialize favourite FTP sites. This is the
 * central point that contains all the IO logic required to
 * retrieve/store/add/edit/delete favouritre FTP sites.
 * 
 * @author Sai Pullabhotla, psai [at] jMethods [dot] com
 * @version 2.0
 */
public class FavoritesManager {

	/**
	 * Serialized file that stores the favourite FTP sites.
	 */
	static final String FILE_NAME = "favorites.ser";

	private static class DataFile {
		private static final File FILE = new File(JFTP.DATA_HOME, FILE_NAME);
	}

	/**
	 * Returns the list of favourite FTP sites. The list is generated by reading
	 * the serialized favorites file.
	 * 
	 * @return List of favourite FTP sites.
	 * @exception IOException
	 *                if an IO error occurs while reading the file
	 * @exception ClassNotFoundException
	 *                We should never get this exception. If we get this, it
	 *                means that the software is not installed correctly.
	 */
	public static List getFavorites() throws IOException,
			ClassNotFoundException, IllegalBlockSizeException,
			BadPaddingException {
		try (var ignored = ProfileStorage.lockActive()) {
			return readFavorites(true);
		}
	}

	private static List readFavorites(boolean sealPlaintext) throws IOException,
			ClassNotFoundException, IllegalBlockSizeException, BadPaddingException {
		checkFavFile();
		Object value;
		try (FileInputStream file = new FileInputStream(DataFile.FILE)) {
			if (file.available() == 0) {
				return new ArrayList();
			}
			try (ObjectInputStream input = new ObjectInputStream(file)) {
				value = input.readObject();
			}
		}
		if (value instanceof List favorites) {
			if (sealPlaintext) {
				writeFavorites(favorites);
			}
			return favorites;
		}
		return (List) ((SealedObject) value).getObject(getCipher(Cipher.DECRYPT_MODE));
	}

	/**
	 * Saves the given list of favourite FTP sites to the favorite file.
	 * 
	 * @param favorites
	 *            List of favorites to be searialized
	 * @exception IOException
	 *                if an IO error occurs
	 */
	public static void saveFavorites(List favorites) throws IOException,
			IllegalBlockSizeException {
		try (var ignored = ProfileStorage.lockActive()) {
			writeFavorites(favorites == null ? new ArrayList() : favorites);
		}
	}

	private static void writeFavorites(List favorites) throws IOException, IllegalBlockSizeException {
		Cipher cipher = getCipher(Cipher.ENCRYPT_MODE);
		Object value = cipher == null ? favorites : new SealedObject((Serializable) favorites, cipher);
		var file = DataFile.FILE.toPath();
		if (Files.isSymbolicLink(file)) {
			file = file.toRealPath();
		}
		ProfileStorage.replace(file, output -> {
			try (ObjectOutputStream stream = new ObjectOutputStream(output)) {
				stream.writeObject(value);
			}
		});
	}

	/**
	 * Adds the given favourite to the list of previously stored favorites and
	 * saves them back to the favorites file.
	 * 
	 * @param host
	 *            Favorite FTP site
	 * @exception IOException
	 *                if an IO error occurs
	 * @exception ClassNotFoundException
	 */
	public static void addFavorite(RemoteHost host) throws IOException,
			ClassNotFoundException, IllegalBlockSizeException,
			BadPaddingException {
		try (var ignored = ProfileStorage.lockActive()) {
			List favorites = readFavorites(false);
			favorites.add(host);
			writeFavorites(favorites);
		}
	}

	private static void checkFavFile() throws IOException {
		if (!DataFile.FILE.exists() || !DataFile.FILE.isFile()) {
			DataFile.FILE.createNewFile();
		}
	}

	static Cipher getCipher(int mode) {
		final byte[] encodedKey = { 28, -9, -23, 35, -93, -47, -28, 55, -83,
				-82, 101, -79, 36, 59, 77, -121 };
		Cipher cipher = null;
		try {
			cipher = Cipher.getInstance("AES");
			SecretKeySpec spec = new SecretKeySpec(encodedKey, "AES");
			cipher.init(mode, spec);
			return cipher;
		} catch (InvalidKeyException exp) {
			exp.printStackTrace();
		} catch (NoSuchAlgorithmException exp) {
			exp.printStackTrace();
		} catch (NoSuchPaddingException exp) {
			exp.printStackTrace();
		}
		return null;
	}
}
